/**
 * @param {object} ctx 景点构建上下文 { project, buildings, theme, spot }
 */
export function createSite(ctx) {
  const { project, buildings } = ctx
  const ll = (list) => list.map(([lon, lat]) => project.toLocal(lon, lat))
  const park = ll(PARK_LL)
  const plaza = ll(PLAZA_LL)
  const gate = ll(GATE_LL)
  // 南大门一带另设一个矩形替换区作保险：门的长轴 61°、进深 151°，沿长轴 u −24～36 m、
  // 进深 v −14～12 m，中心按形心沿两轴平移（u +6、v −1），盖住门体、门前空间与东端岗亭
  // 686460743 一带。现在这一带的 OSM 楼（门体、岗亭）形心都落在园界内，由 park 区替换；
  // 这个矩形让数据重拉、园界微调后门体与门前空间仍被覆盖，不依赖园界恰好包住它们
  const [gx, gz] = centroid(gate)
  const gateZone = rectPolygon(gx + 4.76, gz - 3.78, 60, 26, 61)
  const zones = [park, plaza, gateZone]

  const pb = polygonBounds(park)
  // 园区 2.6 × 2.5 km：1 m 一格（约 2700 × 2540 格、6.9 MB）。kit/grid.js 的盖印只标记格心在半径内的格子，
  // 半径须 ≥ 0.71 × 格宽才可靠：1 m 格下园路半宽（≥ 1.5 m）、实体外扩（0.8 m）都满足；2 m 格会漏盖细路
  const grid = createGrid(
    pb.minX - 40,
    pb.minZ - 40,
    pb.maxX + 40,
    pb.maxZ + 40,
    1
  )
  grid.fillPoly(park, F_PARK)

  const lakes = {
    swan: ll(SWAN_LAKE_LL),
    island: ll(ISLAND_LL),
    ne: ll(NE_LAKE_LL)
  }
  const solids = []
  // footprintNear 的候选楼：形心落在替换区内的 OSM 楼（只有这些会被隐藏、需要被模型取代），
  // 形心预先算好缓存；usedFootprints 记录已被取走的轮廓
  const candidates = []
  for (const i of buildingsInZones(buildings, zones)) {
    const p = buildings[i].p
    if (!p || p.length < 3) continue
    const [cx, cz] = centroid(p)
    candidates.push({ p, cx, cz })
  }
  const usedFootprints = new Set()
  // 林下草地要挖的洞：湖、池在这里先登记，活动场由 addYard 追加
  const lawnHoles = [lakes.swan, lakes.ne, ...WEST_POOLS]
  const gb = new ColorBuilder() // 地面批（单面）：草地、广场、园路、活动场地面
  let camera = null // 到站机位相机位置，cameraPos() 首次调用时算出
  return {
    ctx,
    ll,
    b: new ColorBuilder(), // 主体（landmarkMaterial，双面）
    gb,
    park,
    plaza,
    gate,
    zones,
    grid,
    lakes,
    // 林下草地（buildLawn）要挖的洞：湖、池、活动场。各洞必须互不相交、都在园界内，
    // 否则草地三角剖分会悄悄出错；活动场请用 addYard 登记（带重叠检查）
    lawnHoles,
    // 南门广场（buildPlaza）要挖的洞：草坪岛、喷泉池，由 gate.js 登记。多边形须在广场轮廓内、
    // 彼此不相交；洞里的内容（草坪、水面）由登记方自己画
    plazaHoles: [],
    paths: [], // 已铺园路 { id, pts, w, y, closed }，walkways 按 id 取高度
    // 已登记的实体轮廓（site.solid 写入）：建筑、兽舍、栖架、栈台，也有整块「活动场 + 院墙绿篱」
    // 外扩到绿篱外沿的大轮廓（enclosures.js / nurseries.js）。facingBlocked 拿它判断共墙时，
    // 贴着活动场的墙面也会被当作「贴着邻楼」，不贴窗带
    solids,
    /** 登记实体（建筑、墙、兽舍）：占用栅格打 F_SOLID，并沿边外扩 pad 米（≥ 0.71 m，见上方格宽说明） */
    solid(poly, pad = 0.8) {
      solids.push(poly)
      grid.fillPoly(poly, F_SOLID, pad)
    },
    /**
     * 取 (x, z) 处的 OSM 楼轮廓（数据重拉后 id 与顺序会变，只按坐标找）：
     *   1. 先找轮廓包含 (x, z) 的楼，有多栋时取顶点平均点最近的（不受 maxDist 限制）。
     *      设计文档给的是面积形心，与这里比较用的顶点平均点可差 5～9 m（如熊猫厨房 8.6 m），
     *      只按距离找时，相邻的几栋楼要靠调用顺序才不拿错；面积形心落在自己轮廓里时按包含找最稳。
     *   2. 没有包含它的楼时（凹形楼的面积形心可能在轮廓外），取顶点平均点离 (x, z) 最近且不超过
     *      maxDist 的楼。
     *   都没有时返回 null，调用方用设计文档 3.2 的中心 / 尺寸 / 方位做 rectPolygon 兜底。
     * 环形楼的面积形心会落在院内（可能被院里别的楼包含而取错），这类楼请用常量轮廓（如 MOON_LL）。
     * 只在形心落在替换区内的楼里找（这些楼本来就会被隐藏），且每栋楼只会被取走一次：
     * 已返回过的轮廓不会再返回，两处相邻的取用不会拿到同一栋楼。
     */
    footprintNear(x, z, maxDist = 12) {
      let best = null
      let bestD = Infinity
      for (const c of candidates) {
        if (usedFootprints.has(c) || !pointInPolygon(x, z, c.p)) continue
        const d = Math.hypot(c.cx - x, c.cz - z)
        if (d < bestD) {
          bestD = d
          best = c
        }
      }
      if (!best) {
        bestD = maxDist
        for (const c of candidates) {
          if (usedFootprints.has(c)) continue
          const d = Math.hypot(c.cx - x, c.cz - z)
          if (d <= bestD) {
            bestD = d
            best = c
          }
        }
      }
      if (!best) return null
      usedFootprints.add(best)
      return best.p
    },
    /**
     * 登记一块熊猫活动场（Task 10 用）：在林下草地上开洞、栅格打 F_YARD、把场地地面
     * 挤出到 YARD_Y（草绿色）进地面批。多边形须在园界内，且与其他洞、已铺园路 / 水面 /
     * 其他活动场都不重叠：洞互相重叠会让草地三角剖分悄悄出错，这里只做开发期自检，
     * 发现重叠或越界时 console.warn，不阻断构建。
     * @param {Array<[number, number]>} poly 活动场轮廓（世界坐标 [x, z]）
     */
    addYard(poly) {
      const b = polygonBounds(poly)
      let overlap = 0
      // 逐个 1 m 格心检查：落在活动场内、却已有 F_PAVE / F_WATER / F_YARD 标记的格子数
      for (let x = Math.floor(b.minX) + 0.5; x < b.maxX; x++) {
        for (let z = Math.floor(b.minZ) + 0.5; z < b.maxZ; z++) {
          if (
            grid.get(x, z) & (F_PAVE | F_WATER | F_YARD) &&
            pointInPolygon(x, z, poly)
          ) {
            overlap++
          }
        }
      }
      if (overlap > 0) {
        console.warn(
          `熊猫基地：活动场与已登记的园路 / 水面 / 其他活动场重叠 ${overlap} 格，草地开洞可能出错`
        )
      }
      if (!poly.every(([x, z]) => pointInPolygon(x, z, park))) {
        console.warn("熊猫基地：活动场有顶点落在园界之外，草地开洞可能出错")
      }
      lawnHoles.push(poly)
      grid.fillPoly(poly, F_YARD)
      gb.add(extrudePolygon(poly, [], GROUND_Y, YARD_Y), C.yardGrass)
    },
    // 竹梢顶点按颜色分组（vegetation 写入，最后合成）。活动场里的矮竹（「熊猫食堂」）不走这里：
    // yards.js 自己合成后直接加进了 site.b，vegetation 合成本缓冲时不要再加一遍
    bambooBufs: BAMBOO.map(() => []),
    /**
     * 南大门定位针底座高度（buildGate 返回的左耳顶世界高度 earTop），index.js 在 buildGate 之后写入。
     * 到站机位要用：CityScene 把注视点与相机一起抬高 markerHeight × 0.5
     */
    markerHeight: undefined,
    /**
     * 到站机位的相机位置 [x, y, z]（世界坐标），算法同 CityScene._initTour：
     * 注视点 = 落点 (spot.x, spot.z) + cam.look，相机 = 注视点 + cam.offset，两者都抬高 markerHeight × 0.5。
     * 首次调用时算出并缓存；须在 markerHeight 写入之后调用，否则抛错（构建顺序不对）
     */
    cameraPos() {
      if (camera) return camera
      if (!(this.markerHeight > 0)) {
        throw new Error(
          "熊猫基地：cameraPos 须在 buildGate 写入 markerHeight 之后调用"
        )
      }
      const { spot } = ctx
      const [lx, lz] = spot.cam.look || [0, 0]
      const off = spot.cam.offset
      const lift = this.markerHeight * 0.5
      camera = [spot.x + lx + off[0], lift + off[1], spot.z + lz + off[2]]
      return camera
    },
    /**
     * 点 (x, z) 望向到站机位相机的水平方位角（度，自北顺时针）。透视下各处不同：
     * 核心区各熊猫约 119°～137°（不是统一的机位方位 125°）。熊猫的脸、栖架的正面都朝这里
     */
    bearingToCamera(x, z) {
      const [cx, , cz] = this.cameraPos()
      return (Math.atan2(cx - x, z - cz) / DEG + 360) % 360
    },
    // 受保护的熊猫视线起点（头部，世界坐标 { x, y, z }），由 yards.js 摆熊猫时登记
    viewTargets: [],
    /**
     * 熊猫视线保护（Task 12 种树种竹时对每个树冠、竹丛调用）：球（球心 (cx, cy, cz)、半径 radius）
     * 是否压到某只熊猫望向到站机位的视线。视线 = viewTargets 各点指向 cameraPos() 的线段，
     * 只取头部前方 VIEW.start（1 m）到 VIEW.reach（150 m）一段（取舍见 VIEW 注释）；
     * 球心到线段的距离 < radius 即算挡住。
     * 调用约定：树冠取冠心、半径约 1.15 r；竹丛取半高处为球心、半径约「丛半径 + 半高」。
     * @returns {boolean}
     */
    blocksView(cx, cy, cz, radius) {
      const [px, py, pz] = this.cameraPos()
      for (const t of this.viewTargets) {
        let dx = px - t.x
        let dy = py - t.y
        let dz = pz - t.z
        const len = Math.hypot(dx, dy, dz)
        dx /= len
        dy /= len
        dz /= len
        // 球心在视线上的投影位置（离头部的距离），夹到 [start, reach]
        const s = Math.max(
          VIEW.start,
          Math.min(
            VIEW.reach,
            (cx - t.x) * dx + (cy - t.y) * dy + (cz - t.z) * dz
          )
        )
        const d = Math.hypot(
          cx - (t.x + dx * s),
          cy - (t.y + dy * s),
          cz - (t.z + dz * s)
        )
        if (d < radius) return true
      }
      return false
    }
  }
}
