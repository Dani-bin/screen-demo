def _hd_rgba():
    """高清图（RGBA）仿射到 v2 像素坐标，返回 (BGR 图, 抠图掩码)。"""
    rgba = cv2.imread(HD_IMAGE, cv2.IMREAD_UNCHANGED)       # BGRA
    img = cv2.warpAffine(rgba[..., :3], HD_M, (W, H), flags=cv2.INTER_CUBIC)
    alpha = cv2.warpAffine(rgba[..., 3], HD_M, (W, H)) > 128
    return img, alpha


def outline():
    """沙盘范围：抠图边界去掉小河，取最大连通块的外轮廓（v2 像素，已简化）。"""
    _, alpha = _hd_rgba()
    m = alpha.astype(np.uint8)
    cv2.fillPoly(m, [np.int32(RIVER)], 0)
    m = cv2.morphologyEx(m, cv2.MORPH_OPEN, np.ones((7, 7), np.uint8))
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)
    c = cv2.approxPolyDP(c, 2.0, True).reshape(-1, 2)
    return [(int(x), int(y)) for x, y in c]


# 地块分类代码（与 build_site.CLS 的名字对应）
LC = {"none": 0, "wood": 1, "paddy": 2, "dry": 3, "veg": 4, "pond": 5,
      "hard": 6, "road": 7}


def landcover():
    """逐像素地块分类（v2 像素，uint8，取值见 LC）。

    自动分类：高斯模糊后按超绿指数 2G-R-B 区分绿色（树林 / 稻田），再按局部纹理（9×9 标准差）
    分树林（粗）和稻田草地（细）；R 偏高的黄褐色是旱地 / 菜地；其余是硬地（院坝、厂区、屋顶）。
    暗而平的像素（阴影）不单独成类，用 13×13 邻域里最多的类填上。最后众数平滑，
    再用大田、池塘、公路多边形强制纠正。"""
    img, alpha = _hd_rgba()
    f = cv2.GaussianBlur(img, (0, 0), 2.0).astype(np.float32)
    B, G, R = f[..., 0], f[..., 1], f[..., 2]
    V = f.max(-1) / 255
    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
    mu = cv2.blur(g, (9, 9))
    sd = np.sqrt(np.maximum(cv2.blur(g * g, (9, 9)) - mu * mu, 0))
    sd = cv2.GaussianBlur(sd, (0, 0), 3)
    exg = 2 * G - R - B
    cls = np.zeros((H, W), np.uint8)
    green = exg > 8
    brown = (R > G - 2) & (R > B + 12) & (V > 0.3)
    cls[green & (sd >= 15)] = LC["wood"]
    cls[green & (sd < 15)] = LC["paddy"]
    cls[brown] = LC["dry"]
    cls[(~green) & (~brown) & (V >= 0.33)] = LC["hard"]
    # 阴影（0）：用邻域多数类填上
    out = np.zeros_like(cls)
    best = np.zeros((H, W), np.float32)
    for k in range(1, len(LC)):
        m = ndimage.uniform_filter((cls == k).astype(np.float32), 13)
        out[m > best] = k
        best = np.maximum(best, m)
    # 北边一排人家屋旁的黄褐地块是菜地
    yy = np.arange(H)[:, None]
    out[(out == LC["dry"]) & (yy < VEG_ABOVE_Y)] = LC["veg"]
    for poly, k in ((PADDY_MAIN, "paddy"), (WEST_FIELDS, "paddy"),
                    (POND, "pond"), (ROAD, "road")):
        m = np.zeros((H, W), np.uint8)
        cv2.fillPoly(m, [np.int32(poly)], 1)
        out[m > 0] = LC[k]
    # 蓝线圈定的两片田：按田埂分块后的水稻田 / 菜地整块覆盖（区域里没有林地）
    out[_regions_mask()] = LC["paddy"]
    for kind, _, lab_mask in _plots():
        out[lab_mask] = LC[kind]
    # 我家一带算菜地（房子和门前地坝由 build_site 盖上）；两户人家门前的地坝是硬地
    for poly, k in [(HOME_REAL, "veg")] + [(p_, "hard") for p_ in HD_YARDS]:
        m = np.zeros((H, W), np.uint8)
        cv2.fillPoly(m, [np.int32(poly)], 1)
        out[m > 0] = LC[k]
    out[~alpha] = LC["none"]
    return out


M_PER_PX = 0.2165          # v2 截图比例尺（米 / 像素），与 draw_plan.M_PER_PX 一致
_PLOTS = []


def _regions_mask():
    m = np.zeros((H, W), np.uint8)
    for poly in FIELD_REGIONS:
        cv2.fillPoly(m, [np.int32(poly)], 1)
    return m > 0


def _plots():
    """两片田按田埂切块：区域掩码减去田埂线（2 px 宽），4 连通分块；
    太碎的小块（< 12 m²，多是田埂交叉处的夹角）并给相邻最多的那块。
    返回 [(kind, 面积 m², 掩码)]，kind = paddy（≥ PADDY_MIN_M2）/ veg。结果缓存。"""
    if _PLOTS:
        return _PLOTS
    region = _regions_mask().astype(np.uint8)
    cuts = np.zeros((H, W), np.uint8)
    for pts in FIELD_CUTS:
        cv2.polylines(cuts, [np.int32(pts)], False, 1, thickness=2)
    n, lab = cv2.connectedComponents(region & (1 - cuts), connectivity=4)
    px_m2 = M_PER_PX * M_PER_PX
    areas = np.bincount(lab.ravel(), minlength=n) * px_m2
    # 田埂线本身和碎块：用邻近的大块填上（反复膨胀，直到区域填满）
    keep = np.zeros(n, bool)
    keep[1:] = areas[1:] >= 12.0
    lab = np.where(keep[lab], lab, 0)
    inside = region > 0
    for _ in range(20):
        hole = inside & (lab == 0)
        if not hole.any():
            break
        grown = ndimage.grey_dilation(lab, size=(3, 3))
        lab = np.where(hole, grown, lab)
    areas = np.bincount(lab.ravel(), minlength=n) * px_m2
    for k in range(1, n):
        if not keep[k]:
            continue
        kind = "paddy" if areas[k] >= PADDY_MIN_M2 else "veg"
        for (sx, sy), forced in PLOT_KIND:
            if lab[sy, sx] == k:
                kind = forced
        _PLOTS.append((kind, round(float(areas[k]), 1), lab == k))
    return _PLOTS


def field_plots():
    """[(kind, 面积 m², 外轮廓 v2 像素点列)]，给草图画田块用。"""
    out = []
    for kind, area, m in _plots():
        cs, _ = cv2.findContours(m.astype(np.uint8), cv2.RETR_EXTERNAL,
                                 cv2.CHAIN_APPROX_SIMPLE)
        c = max(cs, key=cv2.contourArea).reshape(-1, 2)
        out.append((kind, area, [(int(x), int(y)) for x, y in c]))
    return out


def field_bunds():
    """FIELD_CUTS 按两片田的范围裁剪后的田埂折线（伸出区域外的部分去掉，
    免得在大田、林地里多出田埂）。逐段每 2 px 采样，连续落在区域内的点连成一条。"""
    inside = cv2.dilate(_regions_mask().astype(np.uint8), np.ones((5, 5), np.uint8)) > 0
    out = []
    for pts in FIELD_CUTS:
        dense = []
        for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
            n = max(1, int(np.hypot(x1 - x0, y1 - y0) / 2))
            dense += [(x0 + (x1 - x0) * t / n, y0 + (y1 - y0) * t / n)
                      for t in range(n)]
        dense.append(pts[-1])
        run = []
        for x, y in dense:
            if inside[int(round(y)), int(round(x))]:
                run.append((round(x, 1), round(y, 1)))
            else:
                if len(run) > 1:
                    out.append(run)
                run = []
        if len(run) > 1:
            out.append(run)
    return out
